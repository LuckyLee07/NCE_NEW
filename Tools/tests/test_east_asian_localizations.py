import json
from pathlib import Path
import plistlib
import sys
import unittest

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import build_east_asian_localizations as builder


class EastAsianLocalizationTests(unittest.TestCase):
    def test_complete_offline_resources(self):
        builder.verify()
        for code in ("ja", "ko"):
            with (builder.APP / f"{code}.lproj/Localizable.strings").open("rb") as stream:
                # OpenStep .strings is validated by plutil/native Foundation, not plistlib.
                self.assertIn("Generated by", stream.read().decode("utf-8"))
            overlay = json.loads((builder.DATA / f"localizations/{code}.json").read_text())
            self.assertEqual(overlay["locale"], code)
            self.assertEqual(overlay["review_status"], "machine_translation_native_review_pending")
            self.assertNotEqual(overlay["word_meanings"]["bank"]["n.河岸"], overlay["word_meanings"]["bank"]["n.银行"])

    def test_ui_overrides_match_generated_tables(self):
        overrides = json.loads((builder.DOCS / "east-asian-overrides.json").read_text())["localizations"]
        for code, entries in overrides.items():
            path = builder.APP / f"{code}.lproj/Localizable.strings"
            expected = builder.strings_file(entries["ui"]).split("\n", 1)[1]
            self.assertEqual(path.read_text().split("\n", 1)[1], expected)
            overlay = json.loads((builder.DATA / f"localizations/{code}.json").read_text())
            for word, translation in entries["words"].items():
                self.assertEqual(overlay["words"][word], translation)
            for key, translation in entries["texts"].items():
                self.assertEqual(overlay["texts"][key], translation)
            for word, variants in entries.get("word_meanings", {}).items():
                for source, translation in variants.items():
                    self.assertEqual(overlay["word_meanings"][word][source], translation)
            for key, translation in entries["sentences"].items():
                self.assertEqual(overlay["sentences"][key], translation)
            for word, source in builder.word_variants():
                translation = entries["texts"].get(builder.POS.sub("", source).strip())
                if translation and word not in entries["words"] and source not in entries.get("word_meanings", {}).get(word, {}):
                    self.assertTrue(overlay["word_meanings"][word][source].endswith(translation), (word, source))
            self.assertNotIn("私の" if code == "ja" else "나의", overlay["words"]["I"])
            self.assertIn("be", overlay["words"]["am"])
            self.assertIn("棚" if code == "ja" else "선반", overlay["words"]["shelf"])
            self.assertIn("税関" if code == "ja" else "세관", overlay["words"]["customs"])

    def test_lightweight_localized_images(self):
        for code in ("ja", "ko"):
            ledger = json.loads((builder.DOCS / f"{code}-images.json").read_text())
            rows = ledger["assets"]
            self.assertEqual(len(rows) + len(ledger.get("reused_originals", [])), len(builder.image_sources()))
            for row in rows:
                self.assertRegex(row["path"], rf"^jpg/localized-[0-9a-f]{{12}}--{code}\.jpg$")
                with Image.open(builder.WORDS / row["path"]) as image:
                    image.load()
                    self.assertEqual(image.size, (128, 128))
                    self.assertEqual(image.format, "JPEG")
                self.assertLessEqual(row["bytes"], 8192)
                self.assertEqual(builder.sha(builder.WORDS / row["source_path"]), row["source_sha256"])

    def test_common_phrase_and_spelling_overrides(self):
        phrases = builder.english_overrides()
        sentences = builder.sources()[2]
        self.assertEqual(phrases["good morning."]["ja"], "おはようございます。")
        for code in ("ja", "ko"):
            overlay = json.loads((builder.DATA / f"localizations/{code}.json").read_text())
            for key, row in sentences.items():
                expected = phrases.get(builder.phrase_key(row["english"]), {}).get(code)
                if expected:
                    self.assertEqual(overlay["sentences"][key], expected)
            self.assertIn("I-N-T-E-L-L-I-G-E-N-T", overlay["sentences"]["N1_L105_第10句"])

    def test_project_and_bundle_languages(self):
        with (builder.APP / "Info.plist").open("rb") as stream:
            info = plistlib.load(stream)
        self.assertEqual(set(info["CFBundleLocalizations"]), {"zh-Hans", "zh-Hant", "ja", "ko"})
        project = (builder.APP.parent / "NCE_ALL.xcodeproj/project.pbxproj").read_text()
        for code in ("ja", "ko"):
            self.assertIn(f'{code}.lproj/Localizable.strings', project)
            self.assertIn(f'{code}.lproj/InfoPlist.strings', project)
        self.assertNotIn("m2m100", project)
        self.assertNotIn("ContentPipeline", project)

    def test_no_known_degenerate_translation_output(self):
        for code in ("ja", "ko"):
            queue = json.loads((builder.DOCS / f"{code}-review-queue.json").read_text())
            self.assertTrue(queue["native_review_required_for_all_new_translations"])
            for section in ("flagged_sentences", "flagged_word_meanings", "flagged_image_captions"):
                for row in queue[section]:
                    self.assertNotIn("repeated_output", row["reasons"], row)


if __name__ == "__main__":
    unittest.main()
