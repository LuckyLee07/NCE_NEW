#!/usr/bin/env python3
"""Build offline Traditional Chinese overlays without changing source content or progress keys."""

import argparse
import hashlib
from importlib import metadata
import json
from pathlib import Path
import re
import sqlite3
import subprocess
import tempfile
import zipfile

from opencc import OpenCC

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "NCE_ALL"
DOCS = ROOT / "Docs/localization"
DATA = APP / "data"
WORDS = DATA / "words"
CONVERTER = OpenCC("s2t")
EXPECTED_OPENCC = "0.1.7"


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def save_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def ui_keys():
    # UI overrides also register keys used through arrays/model values in UIKit.
    # Scanning literal calls alone would silently drop those labels on regeneration.
    keys = set(read_overrides()["ui"])
    for source in APP.rglob("*.m"):
        keys.update(json.loads('"' + match + '"') for match in re.findall(r'NCELocalizedString\(@"((?:[^"\\]|\\.)*)"\)', source.read_text()))
    return keys


def source_texts():
    values = set()
    counts = {}
    with sqlite3.connect(f"file:{DATA / 'NCE.db'}?mode=ro", uri=True) as database:
        lessons = database.execute("SELECT name FROM play_list_lessons").fetchall()
        for (name,) in lessons:
            values.add(name)
            values.update(name.split("－"))
        counts["lesson_records"] = len(lessons)
        rows = database.execute("SELECT word_name, word_translation FROM words ORDER BY id").fetchall()
        values.update(translation for _, translation in rows)
        counts["word_records"] = len(rows)
        counts["unique_words"] = len({word for word, _ in rows})
        for table, column in [("play_learn_mode", "name"), ("word_book", "name_cn"), ("play_list_books", "name")]:
            values.update(value for (value,) in database.execute(f"SELECT {column} FROM {table}") if value)
    sentences = 0
    for book in range(1, 5):
        with zipfile.ZipFile(DATA / f"lesson-packs/book{book}.zip") as archive:
            for name in archive.namelist():
                if not name.endswith(".lrc"):
                    continue
                parts = archive.read(name).decode("utf-8").strip().split("－")
                if len(parts) < 2:
                    raise ValueError(f"Invalid bilingual source: {name}")
                values.add(parts[1])
                sentences += 1
    counts["sentence_records"] = sentences
    editorial = json.loads((WORDS / "editorial-overrides.json").read_text())["overrides"]
    for record in editorial.values():
        values.update(record[field] for field in ("translation", "caption") if record.get(field))
    values.add((WORDS / "licenses/attribution.txt").read_text())
    images = json.loads((ROOT / "Docs/word-resources/generated-images.json").read_text())["assets"]
    values.update(image["caption"] for image in images)
    definitions = dict(rows)
    definitions.update({word: record["translation"] for word, record in editorial.items() if record.get("translation")})
    return values, counts, images, definitions


def read_overrides():
    result = json.loads((DOCS / "overrides.json").read_text())
    if result.get("format_version") != 1 or result.get("locale") != "zh-Hant":
        raise ValueError("Invalid Traditional Chinese override file")
    return result


def convert(text, overrides):
    return overrides.get(text, CONVERTER.convert(text))


def strings_file(values):
    return "/* Generated by Tools/build_chinese_localizations.py. Edit Docs/localization/overrides.json. */\n" + "".join(
        f"{json.dumps(key, ensure_ascii=False)} = {json.dumps(value, ensure_ascii=False)};\n" for key, value in sorted(values.items()))


def preserved_sources():
    paths = [DATA / "NCE.db", *(DATA / f"lesson-packs/book{book}.zip" for book in range(1, 5))]
    paths.extend((WORDS / "jpg").glob("*.jpg"))
    paths.extend((WORDS / "wav").glob("*.wav"))
    return {str(path.relative_to(ROOT)): sha(path) for path in paths
            if not re.fullmatch(r"localized-[0-9a-f]{12}--(?:hant|ja|ko)\.jpg", path.name)}


def audit_original_images(temporary, generated):
    generated_paths = {asset["path"] for asset in generated}
    index = json.loads((WORDS / "resource-index.json").read_text())["words"]
    paths = sorted({record["image"] for record in index.values()} - generated_paths)
    cache_path = DOCS / "original-image-text-audit.json"
    cache = json.loads(cache_path.read_text()) if cache_path.exists() else {"images": {}}
    missing = [relative for relative in paths if cache["images"].get(relative, {}).get("sha256") != sha(WORDS / relative)]
    if missing:
        executable = temporary / "ocr"
        subprocess.run(["xcrun", "clang", "-fobjc-arc", "-framework", "Foundation", "-framework", "Vision", str(ROOT / "Tools/audit_image_chinese.m"), "-o", str(executable)], check=True)
        jobs, output = temporary / "ocr-input.json", temporary / "ocr-output.json"
        save_json(jobs, [str(WORDS / relative) for relative in missing])
        subprocess.run([str(executable), str(jobs), str(output)], check=True)
        scanned = json.loads(output.read_text())
        for relative in missing:
            cache["images"][relative] = {"sha256": sha(WORDS / relative), **scanned[str(WORDS / relative)]}
    cache.update({"format_version": 1, "method": "Apple Vision accurate OCR zh-Hans/zh-Hant/en-US; OCR is not human visual approval"})
    save_json(cache_path, cache)
    candidates = {word: record["image"] for word, record in index.items() if cache["images"].get(record["image"], {}).get("contains_chinese")}
    decisions = json.loads((DOCS / "original-image-decisions.json").read_text())["decisions"]
    if set(candidates) != set(decisions) or any(record["action"] not in ("reuse", "meaning_card") for record in decisions.values()):
        raise ValueError("OCR candidate decisions need visual triage before building")
    return {word: path for word, path in candidates.items() if decisions[word]["action"] == "meaning_card"}


def build_images(temporary, generated, texts, original_chinese, definitions):
    old_path = DOCS / "generated-images.json"
    old = json.loads(old_path.read_text()) if old_path.exists() else {"assets": []}
    previous = {asset["path"]: asset for asset in old["assets"]}
    jobs, assets, mapping = [], [], {}
    originals = {asset["word"]: asset for asset in generated}
    for word in sorted(set(originals) | set(original_chinese)):
        source = originals.get(word)
        if source:
            caption = texts[source["caption"]]
            if caption == source["caption"] and source["kind"] != "meaning_card":
                continue
            job = {key: source[key] for key in ("kind", "word", "diagram", "icons", "generated_source") if key in source}
            source_path = source["path"]
            source_sha = sha(WORDS / source_path)
        else:
            source_path = original_chinese[word]
            source_sha = sha(WORDS / source_path)
            caption = texts[definitions[word]]
            job = {"word": word, "kind": "meaning_card"}
        token = hashlib.sha256(word.encode()).hexdigest()[:12]
        relative = f"jpg/localized-{token}--hant.jpg"
        job.update({"caption": caption, "card_title": "釋義卡", "path": relative, "source_path": source_path,
                    "source_sha256": source_sha, "review_status": "native_editorial_review_pending"})
        path = WORDS / relative
        if job.get("generated_source"):
            job["source_image"] = str(ROOT / "ContentPipeline/word-images" / job["generated_source"])
        existing = previous.get(relative)
        recipe = {key: value for key, value in job.items() if key != "source_image"}
        if path.exists():
            if not existing or sha(path) != existing["sha256"]:
                raise ValueError(f"Refusing to overwrite unrecorded/modified picture: {path}")
            if all(existing.get(key) == value for key, value in recipe.items()):
                assets.append(existing)
                mapping[word] = relative
                continue
        jobs.append({**job, "output": str(temporary / path.name)})
        mapping[word] = relative
    if jobs:
        executable = temporary / "renderer"
        subprocess.run(["xcrun", "clang", "-fobjc-arc", "-framework", "AppKit", str(ROOT / "Tools/render_word_image.m"), "-o", str(executable)], check=True)
        for offset in range(0, len(jobs), 100):
            batch = jobs[offset:offset + 100]
            save_json(temporary / "jobs.json", batch)
            subprocess.run([str(executable), str(temporary / "jobs.json"), str(ROOT / "ContentPipeline/word-images/twemoji")], check=True)
            for job in batch:
                path = WORDS / job["path"]
                if path.exists() and sha(path) != previous[job["path"]]["sha256"]:
                    raise ValueError("Picture changed during generation")
                Path(job["output"]).replace(path)
                asset = {key: value for key, value in job.items() if key not in ("output", "source_image")}
                asset.update({"sha256": sha(path), "bytes": path.stat().st_size, "width": 128, "height": 128})
                assets.append(asset)
    # Remove only unchanged, pipeline-owned variants that no longer belong to the overlay.
    retained = set(mapping.values())
    for relative, asset in previous.items():
        path = WORDS / relative
        if relative not in retained and path.exists():
            if not re.fullmatch(r"jpg/localized-[0-9a-f]{12}--hant\.jpg", relative) or sha(path) != asset["sha256"]:
                raise ValueError(f"Refusing to remove modified/unowned picture: {path}")
            path.unlink()
    ledger = {"format_version": 1, "locale": "zh-Hant", "jpeg_quality": 0.55, "max_bytes_per_image": 8192,
              "assets": sorted(assets, key=lambda asset: asset["word"])}
    save_json(old_path, ledger)
    return mapping, ledger


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verify", action="store_true", help="Check generated text resources without writing")
    args = parser.parse_args()
    if metadata.version("opencc-python-reimplemented") != EXPECTED_OPENCC:
        raise ValueError("Use the pinned build-only dependency in Tools/localization_requirements.txt")
    overrides = read_overrides()
    values, counts, generated, definitions = source_texts()
    texts = {value: convert(value, overrides["texts"]) for value in sorted(values)}
    keys = ui_keys()
    simplified = {key: key for key in keys}
    traditional = {key: convert(key, {**overrides["texts"], **overrides["ui"]}) for key in keys}
    for key, value in traditional.items():
        if re.findall(r"%(?:@|[dflu]+)", key) != re.findall(r"%(?:@|[dflu]+)", value):
            raise ValueError(f"Format placeholders changed: {key}")
    expected = {}
    for language, table, name in [("zh-Hans", simplified, "新概念全四册"), ("zh-Hant", traditional, "新概念全四冊")]:
        expected[APP / f"{language}.lproj/Localizable.strings"] = strings_file(table)
        expected[APP / f"{language}.lproj/InfoPlist.strings"] = strings_file({"CFBundleDisplayName": name})
    if args.verify:
        for path, value in expected.items():
            if not path.exists() or path.read_text() != value:
                raise ValueError(f"Outdated localization: {path}")
        content = json.loads((DATA / "localizations/zh-Hant.json").read_text())
        if content["texts"] != texts:
            raise ValueError("Traditional content overlay is stale")
        ledger = json.loads((DOCS / "generated-images.json").read_text())
        if content["images"] != {asset["word"]: asset["path"] for asset in ledger["assets"]}:
            raise ValueError("Traditional image mapping differs from ledger")
        for asset in ledger["assets"]:
            if sha(WORDS / asset["path"]) != asset["sha256"] or (WORDS / asset["path"]).stat().st_size > 8192:
                raise ValueError(f"Changed or oversized localized picture: {asset['word']}")
        if json.loads((DOCS / "preserved-sources.json").read_text()) != preserved_sources():
            raise ValueError("A preserved database, lesson archive, audio or source image changed")
        print(json.dumps({"verified": True, **counts, "ui_strings": len(keys), "text_entries": len(texts), "localized_pictures": len(ledger["assets"])}))
        return
    before = preserved_sources()
    with tempfile.TemporaryDirectory(prefix="nce-localization-") as directory:
        temporary = Path(directory)
        original_chinese = audit_original_images(temporary, generated)
        image_mapping, image_ledger = build_images(temporary, generated, texts, original_chinese, definitions)
    for path, value in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(value, encoding="utf-8")
    content = {"format_version": 1, "locale": "zh-Hant", "texts": texts, "images": image_mapping}
    save_json(DATA / "localizations/zh-Hant.json", content)
    if before != preserved_sources():
        raise ValueError("A source resource changed during localization")
    save_json(DOCS / "preserved-sources.json", before)
    report = {"format_version": 1, "locale": "zh-Hant", "converter": "opencc-python-reimplemented", "converter_version": EXPECTED_OPENCC,
              "conversion": "s2t plus explicit editorial/UI overrides", **counts, "ui_strings": len(keys), "text_entries": len(texts),
              "localized_pictures": len(image_ledger["assets"]), "localized_picture_bytes": sum(asset["bytes"] for asset in image_ledger["assets"]),
              "original_picture_chinese_words": len(original_chinese), "source_resources_unchanged": True,
              "native_editorial_review": "pending", "original_courses_bundled": False}
    save_json(DOCS / "build-report.json", report)
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
